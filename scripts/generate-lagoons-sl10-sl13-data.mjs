import { readFile, writeFile } from "node:fs/promises";

const phases = [
  { label: "sl10", phase: "SL10", title: "Hidden Phase SL10", range: "SDE3_1982–SDE3_1999" },
  { label: "sl13", phase: "SL13", title: "Phase SL13", range: "SDE3_1966–SDE3_1981" },
];
const output = new URL("../client/src/data/lagoonsDcrPhases.ts", import.meta.url);

async function storageMap(label) {
  const raw = await readFile(new URL(`../tmp/${label}-dcrs/upload-results.txt`, import.meta.url), "utf8");
  const lines = raw.split(/\r?\n/);
  const map = new Map();
  let dcrId = null;
  for (const line of lines) {
    const upload = line.match(/\/([^/]+\.pdf)\s+\(size:/);
    if (upload) dcrId = upload[1].replace(/\.pdf$/i, "");
    const stored = line.match(/Storage Path:\s*(\/manus-storage\/\S+)/);
    if (stored && dcrId) map.set(dcrId, stored[1]);
  }
  return map;
}

async function phaseRecords(config) {
  const extracted = JSON.parse(await readFile(new URL(`../tmp/${config.label}-dcrs/extracted-records.json`, import.meta.url), "utf8"));
  const urls = await storageMap(config.label);
  const records = extracted.records
    .filter((record) => record.parseStatus === "complete" && record.aldarPhase === config.phase)
    .map((record) => {
      const dcrUrl = urls.get(record.dcrId);
      if (!dcrUrl) throw new Error(`Missing permanent storage URL for ${record.dcrId}`);
      return {
        villaKey: `lagoons-${config.phase.toLowerCase()}/plot-${record.admPlotId}`,
        dcrId: record.dcrId,
        plotNumber: record.admPlotId,
        aldarPlotId: record.aldarPlotId,
        phase: config.phase,
        typology: record.typology,
        landSqm: record.plotAreaSqm,
        landSqft: record.plotAreaSqft,
        maxGfaSqm: record.maxGfaSqm,
        maxGfaSqft: record.maxGfaSqm ? Math.round(record.maxGfaSqm * 10.7639104167 * 100) / 100 : null,
        latitude: record.centroid.lat,
        longitude: record.centroid.lng,
        boundary: record.boundary,
        dcrUrl,
        dmtUrl: record.dmtUrl,
        googleMapsUrl: record.googleMapsUrl,
        coordinateSource: "official_dcr_centroid",
        availability: "unknown",
      };
    })
    .sort((a, b) => a.plotNumber - b.plotNumber);
  if (records.length === 0) throw new Error(`No ${config.phase} records generated`);
  const keys = new Set(records.map((record) => record.villaKey));
  if (keys.size !== records.length) throw new Error(`Duplicate ${config.phase} villa keys`);
  return records;
}

const sl10 = await phaseRecords(phases[0]);
const sl13 = await phaseRecords(phases[1]);
const code = `// Generated by scripts/generate-lagoons-sl10-sl13-data.mjs from official DMT DCRs.\n\nexport type LagoonsDcrPhasePlot = {\n  villaKey: string;\n  dcrId: string;\n  plotNumber: number;\n  aldarPlotId: string;\n  phase: "SL10" | "SL13";\n  typology: string | null;\n  landSqm: number;\n  landSqft: number;\n  maxGfaSqm: number | null;\n  maxGfaSqft: number | null;\n  latitude: number;\n  longitude: number;\n  boundary: { lat: number; lng: number }[];\n  dcrUrl: string;\n  dmtUrl: string;\n  googleMapsUrl: string;\n  coordinateSource: "official_dcr_centroid";\n  availability: "unknown";\n};\n\nexport const LAGOONS_SL10_PLOTS: LagoonsDcrPhasePlot[] = ${JSON.stringify(sl10, null, 2)};\n\nexport const LAGOONS_SL13_PLOTS: LagoonsDcrPhasePlot[] = ${JSON.stringify(sl13, null, 2)};\n\nexport const LAGOONS_DCR_PHASE_SUMMARIES = {\n  SL10: { projectName: "Saadiyat Lagoons · Hidden Phase SL10", phase: "SL10", sourceRange: "SDE3_1982–SDE3_1999", officialPlotCount: LAGOONS_SL10_PLOTS.length },\n  SL13: { projectName: "Saadiyat Lagoons · Phase SL13", phase: "SL13", sourceRange: "SDE3_1966–SDE3_1981", officialPlotCount: LAGOONS_SL13_PLOTS.length },\n} as const;\n`;
await writeFile(output, code);
