import { readFile, stat, writeFile } from "node:fs/promises";

const extractedPath = new URL("../tmp/sl9-dcrs/extracted-records.json", import.meta.url);
const storageMapPath = new URL("../tmp/sl9-dcrs/sl9-storage-map.tsv", import.meta.url);
const outputPath = new URL("../client/src/data/lagoonsHiddenSl9.ts", import.meta.url);
const sqlPath = new URL("../tmp/sl9-dcrs/register-villa-files.sql", import.meta.url);
const pdfDir = new URL("../tmp/sl9-dcrs/pdfs/", import.meta.url);

function quoteSql(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

async function main() {
  const extracted = JSON.parse(await readFile(extractedPath, "utf8"));
  const storageMap = new Map(
    (await readFile(storageMapPath, "utf8"))
      .trim()
      .split("\n")
      .filter(Boolean)
      .map((line) => line.split("\t")),
  );
  const records = extracted.records
    .filter((record) => record.parseStatus === "complete" && record.aldarPhase === "SL9")
    .map((record) => {
      const storageUrl = storageMap.get(record.dcrId);
      if (!storageUrl) throw new Error(`No permanent storage URL for ${record.dcrId}`);
      return {
        villaKey: `lagoons-hidden-sl9/plot-${record.admPlotId}`,
        dcrId: record.dcrId,
        plotNumber: record.admPlotId,
        aldarPlotId: record.aldarPlotId,
        phase: record.aldarPhase,
        typology: record.typology,
        landSqm: record.plotAreaSqm,
        landSqft: record.plotAreaSqft,
        maxGfaSqm: record.maxGfaSqm,
        maxGfaSqft: record.maxGfaSqm ? Math.round(record.maxGfaSqm * 10.7639104167 * 100) / 100 : null,
        latitude: record.centroid.lat,
        longitude: record.centroid.lng,
        boundary: record.boundary,
        dcrUrl: storageUrl,
        dmtUrl: record.dmtUrl,
        googleMapsUrl: record.googleMapsUrl,
        coordinateSource: "official_dcr_centroid",
        availability: "unknown",
      };
    })
    .sort((a, b) => a.plotNumber - b.plotNumber);
  const duplicateKeys = records.filter((record, index) => index > 0 && record.villaKey === records[index - 1].villaKey);
  if (records.length !== 257 || duplicateKeys.length) {
    throw new Error(`Expected 257 unique SL9 records, received ${records.length}, duplicates ${duplicateKeys.length}`);
  }

  const code = `// Generated by scripts/generate-lagoons-hidden-sl9-data.mjs from official DCRs.\n\nexport type LagoonsHiddenSl9Plot = {\n  villaKey: string;\n  dcrId: string;\n  plotNumber: number;\n  aldarPlotId: string;\n  phase: "SL9";\n  typology: string | null;\n  landSqm: number;\n  landSqft: number;\n  maxGfaSqm: number | null;\n  maxGfaSqft: number | null;\n  latitude: number;\n  longitude: number;\n  boundary: { lat: number; lng: number }[];\n  dcrUrl: string;\n  dmtUrl: string;\n  googleMapsUrl: string;\n  coordinateSource: "official_dcr_centroid";\n  availability: "unknown";\n};\n\nexport const LAGOONS_HIDDEN_SL9_PLOTS: LagoonsHiddenSl9Plot[] = ${JSON.stringify(records, null, 2)};\n\nexport const LAGOONS_HIDDEN_SL9_SUMMARY = {\n  projectName: "Saadiyat Lagoons · Hidden Phase SL9",\n  phase: "SL9",\n  officialPlotCount: LAGOONS_HIDDEN_SL9_PLOTS.length,\n  sourceRange: "SDE3_2000–SDE3_2407",\n  directCoordinateCount: LAGOONS_HIDDEN_SL9_PLOTS.length,\n  availabilityStatus: "unknown" as const,\n};\n`;
  await writeFile(outputPath, code);
  await Promise.all(records.map(async (record) => {
    record.sizeBytes = (await stat(new URL(`${record.dcrId}.pdf`, pdfDir))).size;
  }));

  const sqlRows = records.map((record) => {
    const fileName = `${record.dcrId}.pdf`;
    const storageKey = record.dcrUrl.replace(/^\/manus-storage\//, "");
    return `('villa', ${quoteSql(record.villaKey)}, 'dcr', ${quoteSql(fileName)}, 'application/pdf', ${record.sizeBytes}, ${quoteSql(storageKey)}, ${quoteSql("Official DMT DCR · Saadiyat Lagoons SL9")}, 1, ${quoteSql("Ayman Sadieh")})`;
  });
  const sql = `INSERT INTO villa_files (scope, villaKey, category, filename, mimeType, sizeBytes, storageKey, description, uploadedBy, uploaderName) VALUES\n${sqlRows.join(",\n")}\nON DUPLICATE KEY UPDATE villaKey = VALUES(villaKey), category = VALUES(category), filename = VALUES(filename), mimeType = VALUES(mimeType), sizeBytes = VALUES(sizeBytes), description = VALUES(description), uploadedBy = VALUES(uploadedBy), uploaderName = VALUES(uploaderName);\n`;
  await writeFile(sqlPath, sql);
  console.log(JSON.stringify({ records: records.length, output: outputPath.pathname, sql: sqlPath.pathname }));
}

await main();
